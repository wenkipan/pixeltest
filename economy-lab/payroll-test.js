"use strict";
const assert = require("node:assert/strict");
const { BUILDINGS, currentNetValue, work, newWorld, step, simulate } = require("./payroll");
assert.equal(Object.keys(BUILDINGS).length, 6);
assert.deepEqual(BUILDINGS.mill.input,{electricity:1,barley:1});
assert.deepEqual(BUILDINGS.farm.output,{barley:1});
assert.deepEqual(BUILDINGS.riceField.output,{rice:3});
assert.deepEqual(BUILDINGS.bakery.output,{bread:2});
assert.deepEqual(BUILDINGS.sand.output,{cement:2});
assert.deepEqual(BUILDINGS.ironMine.output,{iron:2});
assert.equal(BUILDINGS.bakery.build.laborHours,12);
assert.equal(BUILDINGS.bakery.san,10);
const w=newWorld(6), initial=w.owner.gold+w.workers.reduce((s,n)=>s+n.gold,0);
const one=step(w);
assert.equal(one.hired,true);
assert.equal(one.wagePaid,6);
assert.equal(w.stock.flour,99);
assert.equal(w.stock.water,99);
assert.equal(w.stock.electricity,198);
assert.equal(w.workers.reduce((s,n)=>s+n.gold,0)>0,true);
assert.ok(Math.abs(one.totalGold-initial)<1e-8);
const noWork=simulate(0,30), withWages=simulate(6,30);
assert.equal(noWork.totalJobs,0);
assert.equal(noWork.ending.zeroHunger,5);
assert.equal(withWages.totalJobs,30);
assert.equal(withWages.ending.zeroHunger,0);
assert.ok(withWages.ending.price>0);
assert.ok(withWages.history.every(d=>Math.abs(d.totalGold-100)<1e-8));
const eventually=simulate(6,120);
assert.equal(eventually.totalJobs,100);
assert.equal(eventually.ending.zeroHunger,5);
console.log("Wage and building-recipe tests passed.");
